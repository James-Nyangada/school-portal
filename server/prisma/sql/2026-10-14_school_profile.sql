-- School profile: public school information for the website, plus academic calendar (term dates). Safe to re-run.

CREATE TABLE IF NOT EXISTS "SchoolProfile" (
    "id" INTEGER NOT NULL DEFAULT 1,
    "name" TEXT NOT NULL DEFAULT '',
    "shortName" TEXT,
    "motto" TEXT,
    "tagline" TEXT,
    "logoUrl" TEXT,
    "heroImageUrl" TEXT,
    "foundedYear" INTEGER,
    "registrationNumber" TEXT,
    "curriculum" TEXT,
    "schoolType" TEXT,
    "gender" TEXT,
    "levelsOffered" TEXT,
    "about" TEXT,
    "history" TEXT,
    "mission" TEXT,
    "vision" TEXT,
    "coreValues" JSONB NOT NULL DEFAULT '[]',
    "principalName" TEXT,
    "principalTitle" TEXT,
    "principalPhotoUrl" TEXT,
    "principalMessage" TEXT,
    "email" TEXT,
    "phone" TEXT,
    "altPhone" TEXT,
    "whatsapp" TEXT,
    "postalAddress" TEXT,
    "physicalAddress" TEXT,
    "county" TEXT,
    "mapUrl" TEXT,
    "officeHours" TEXT,
    "website" TEXT,
    "socialLinks" JSONB NOT NULL DEFAULT '{}',
    "highlights" JSONB NOT NULL DEFAULT '[]',
    "facilities" JSONB NOT NULL DEFAULT '[]',
    "admissionsOpen" BOOLEAN NOT NULL DEFAULT false,
    "admissionsInfo" TEXT,
    "admissionRequirements" JSONB NOT NULL DEFAULT '[]',
    "academicYear" TEXT,
    "terms" JSONB NOT NULL DEFAULT '[]',
    "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "SchoolProfile_pkey" PRIMARY KEY ("id")
);
